// Generates the BRQ vector logos used by the frontend.
//   node tools/brq/gen_logo.mjs
// Writes:
//   frontend/public/img/BRQ_Logo_Flat.svg  - single-colour wordmark, <symbol id="logo">, viewBox 768x264
//                                             (fill is inherited, so CSS `fill:` on the <svg> colours it)
//   frontend/src/lib/brqLogoPaths.ts       - the same geometry for inline, gradient-filled use
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const f = (n) => Number(n.toFixed(2));

// ---- Mark: broken hexagon ring + lightning bolt, designed in a 100x100 box ----
const C = 50, R = 46, r = 37.5;
const hex = (rad) =>
  Array.from({ length: 6 }, (_, k) => {
    const a = ((-90 + 60 * k) * Math.PI) / 180;
    return [C + rad * Math.cos(a), C + rad * Math.sin(a)];
  });
const O = hex(R), I = hex(r);
const lerp = (p, q, t) => [p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t];
// Which part of each edge (V_k -> V_k+1) to keep. Gaps let the bolt break through.
const keep = [
  [[0, 0.1], [0.6, 1]], // top-right edge: gap where the bolt's head exits
  [[0, 1]],
  [[0, 1]],
  [[0, 0.1], [0.5, 1]], // bottom-left edge: gap where the bolt's tip exits
  [[0, 1]],
  [[0, 1]],
];
const ring = [];
for (let k = 0; k < 6; k++) {
  const n = (k + 1) % 6;
  for (const [a, b] of keep[k]) {
    const pts = [lerp(O[k], O[n], a), lerp(O[k], O[n], b), lerp(I[k], I[n], b), lerp(I[k], I[n], a)];
    ring.push("M" + pts.map((p) => `${f(p[0])} ${f(p[1])}`).join("L") + "Z");
  }
}
const ringPath = ring.join("");
const boltPath = "M57 2L74 2L61 39L75 39L33 99L45 58L29 58Z";

// ---- Wordmark letters "BRQ", angular style, in the 768x264 wordmark box ----
const B =
  "M290 40L405 40L430 65L430 112L417 132L430 152L430 199L405 224L290 224Z" +
  "M322 70L392 70L398 76L398 108L392 114L322 114Z" +
  "M322 150L392 150L398 156L398 188L392 194L322 194Z";
const Rl =
  "M454 40L569 40L594 65L594 118L577 136L598 224L563 224L545 148L486 148L486 224L454 224Z" +
  "M486 70L556 70L562 76L562 112L556 118L486 118Z";
const Qring =
  "M643 40L743 40L768 65L768 199L743 224L643 224L618 199L618 65Z" +
  "M656 72L730 72L736 78L736 186L730 192L656 192L650 186L650 78Z";
const Qtail = "M694 166L724 166L766 236L736 236Z";

// Mark sits in the first 240 units of the wordmark, vertically centred.
const markXform = "translate(4 12) scale(2.4)";

const flat = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 768 264">
  <!-- BRQ wordmark. Generated by tools/brq/gen_logo.mjs - edit that, not this. -->
  <symbol id="logo" viewBox="0 0 768 264">
    <g transform="${markXform}"><path d="${ringPath}"/><path d="${boltPath}"/></g>
    <path fill-rule="evenodd" d="${B}"/>
    <path fill-rule="evenodd" d="${Rl}"/>
    <path fill-rule="evenodd" d="${Qring}"/>
    <path d="${Qtail}"/>
  </symbol>
  <use href="#logo"/>
</svg>
`;
writeFileSync(resolve(root, "frontend/public/img/BRQ_Logo_Flat.svg"), flat);

const ts = `// Generated by tools/brq/gen_logo.mjs - edit that, not this.
/** Mark geometry, 100x100 box. */
export const BRQ_RING_PATH = "${ringPath}";
export const BRQ_BOLT_PATH = "${boltPath}";
/** Wordmark geometry, 768x264 box; the mark is placed with BRQ_MARK_TRANSFORM. */
export const BRQ_MARK_TRANSFORM = "${markXform}";
export const BRQ_LETTER_PATHS: string[] = ["${B}", "${Rl}", "${Qring}", "${Qtail}"];
`;
writeFileSync(resolve(root, "frontend/src/lib/brqLogoPaths.ts"), ts);
console.log("ok");
